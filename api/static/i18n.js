window.currentLanguage = "ru";

window.setLanguage = function (lang) {
    if (translations[lang]) {
        window.currentLanguage = lang;
        applyTranslations();

        // Dynamically rebuild cart and grids if scripts are loaded
        if (window.refreshCart) window.refreshCart();
        if (window.syncProductButtons) window.syncProductButtons();
        
        // Force refresh deliveries if actively open
        if (document.getElementById('today')?.style.display === 'block' && typeof loadDeliveries === 'function') {
            loadDeliveries('today');
        } else if (document.getElementById('history')?.style.display === 'block' && typeof loadDeliveries === 'function') {
            loadDeliveries('history');
        }

        // Apply visual tick in settings
        document.querySelectorAll('.lang-btn').forEach(btn => {
            btn.classList.remove('active');
            btn.innerHTML = btn.innerHTML.replace(' ✓', '');
            if (btn.dataset.lang === lang) {
                btn.classList.add('active');
                if (!btn.innerHTML.includes('✓')) {
                    btn.innerHTML += ' ✓';
                }
            }
        });
    }
};

window.applyTranslations = function () {
    const langObj = translations[window.currentLanguage];
    if (!langObj) return;

    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (langObj[key]) {
            if (el.tagName === 'INPUT' && el.type === 'text') {
                el.placeholder = langObj[key];
            } else {
                el.textContent = langObj[key];
            }
        }
    });

    // Handle cart title text separately if needed because of numbers,
    // though ideally the number is in a <span>. I'll rely on script hooks that set .textContent explicitly
    // and replace them with calls to translation.
};

window.t = function (key) {
    return translations[window.currentLanguage]?.[key] || key;
};
